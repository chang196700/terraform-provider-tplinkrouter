func deviceDocument() string {
	b := heading("tplinkrouter_device (Data Source)", "读取设备型号、固件、能力模块和配置保存状态；不修改或保存配置。")
	b.WriteString("\n## 属性\n\n| 属性 | Terraform 类型 | 要求 | 敏感 | 说明 |\n| --- | --- | --- | --- | --- |\n")
	for _, field := range []struct{ name, kind, description string }{
		{"id", "string", "设备连接标识。"}, {"model", "string", "设备型号。"}, {"hardware_version", "string", "硬件版本。"}, {"firmware_version", "string", "固件版本与构建号。"}, {"capabilities", "list(string)", "固件公开的能力模块名称。"}, {"configuration_status", "string", "当前配置是否已保存，例如 Saved 或 Not Saved。"},
	} {
		writeFieldRow(b, field.name, field.kind, "只读", false, field.description)
	}
	b.WriteString("\n## 范围与来源\n\n读取 `device_info.info`、`function.new_module_spec` 与 `system.cfg_status`。这些查询来自管理首页及 `/web-static/js/su/su.js`。数据源不支持导入，也没有配置写入行为。\n")
	return b.String()
}

func capabilitiesDocument(specs []catalog.Spec, resources int, report auditReport, results map[string]auditResult) string {
	b := heading("TL-ER6220T 能力目录", "此矩阵由强类型 catalog 生成；每个配置类型具有独立 schema，不提供通用 JSON 写入接口。")
	fmt.Fprintf(b, "\n共 %d 个资源和 %d 个数据源。范围是声明式配置与只读状态；重启、恢复出厂、固件升级、诊断执行和云账号绑定等一次性操作不作为资源。\n", resources, len(specs)+1)
	b.WriteString("\n资源接口已实现与设备写入已验证是不同的结论：本次真实设备验证限制为只读。空表读取成功不能证明创建或更新的全部字段可用。字段缺失可能与固件能力、当前工作模式或未启用功能有关。\n")
	if report.GeneratedAt != "" {
		fmt.Fprintf(b, "\n只读审计快照：%s；设备 `%s`，硬件 `%s`，固件 `%s`。矩阵状态仅指读取结果，完整脱敏报告由本地 `.cache/catalog-audit.json` 保存。\n", report.GeneratedAt, report.Model, report.Hardware, report.Firmware)
	}
	b.WriteString("\n| 配置类型 | 分类 | 资源 | 数据源 | 管理方式 | 固件能力条件 | 只读验证 | 页面证据 |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	b.WriteString("| administrator | System | [参考](resources/administrator.md) | — | 单例凭据 | — | 专用适配器 | `/userrpm/account_config.htm` |\n")
	b.WriteString("| device | System | — | [参考](data-sources/device.md) | 设备信息 | — | 设备发现 | 管理首页 |\n")
	ordered := append([]catalog.Spec(nil), specs...)
	sort.Slice(ordered, func(i, j int) bool {
		left, right := strings.ToLower(ordered[i].Category), strings.ToLower(ordered[j].Category)
		if left != right {
			return left < right
		}
		return ordered[i].Name < ordered[j].Name
	})
	for _, spec := range ordered {
		resource := "—"
		if !spec.DataSourceOnly {
			resource = fmt.Sprintf("[参考](resources/%s.md)", spec.Name)
		}
		status := "未纳入快照"
		if result, exists := results[spec.Name]; exists {
			switch result.Status {
			case "SUCCESS":
				status = fmt.Sprintf("读取成功（%d 条）", result.Rows)
			case "UNAVAILABLE":
				status = "设备未公开能力"
			default:
				status = "读取失败"
				if result.ErrorCode != nil {
					status += fmt.Sprintf("（%d）", *result.ErrorCode)
				}
			}
		}
		capability := "—"
		if spec.Capability != "" {
			capability = "`" + spec.Capability + "`"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | [参考](data-sources/%s.md) | `%s` | %s | %s | `%s` |\n", spec.Name, cell(spec.Category), resource, spec.Name, spec.Mode, capability, status, cell(sourcePath(spec.Source)))
	}
	b.WriteString("\n## 维护此目录\n\n```shell\n# 默认只生成本地文档，不读取凭据或连接路由器\ngo run ./cmd/catalog\n\n# 明确发起只读审计；HTTP/HTTPS 均不会降级重试\ngo run ./cmd/catalog audit -endpoint https://192.168.1.1 -env-file .env -insecure-skip-verify -allow-legacy-tls\n\n# 将已有的脱敏审计结果注入目录矩阵，仍然不连接设备\ngo run ./cmd/catalog generate -audit .cache/catalog-audit.json\n```\n\n审计客户端强制 `ReadOnly=true`，只允许登录、查询和注销。报告记录条数、字段名、错误码与设备版本，不记录配置字段值、账号、密码或会话 token。默认保持 TLS 证书验证开启；示例中的两个 TLS 开关是对此固件明确指定的兼容选项。\n")
	return b.String()
}

