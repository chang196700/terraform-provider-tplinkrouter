const generatedMarker = "<!-- Generated by go run ./cmd/catalog. Edit the catalog or generator, then regenerate. -->"

func generateCommand(args []string) error {
	flags := flag.NewFlagSet("generate", flag.ContinueOnError)
	output := flags.String("out", "docs", "Documentation output directory")
	auditPath := flags.String("audit", "", "Optional sanitized audit report to annotate the capability matrix")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return errors.New("generate does not accept positional arguments")
	}
	specs, err := specsSorted()
	if err != nil {
		return err
	}
	results := map[string]auditResult{}
	var report auditReport
	if *auditPath != "" {
		content, err := os.ReadFile(*auditPath)
		if err != nil {
			return errors.New("cannot read the supplied audit report")
		}
		if err := json.Unmarshal(content, &report); err != nil || !report.ReadOnly {
			return errors.New("supplied audit report is invalid or was not marked read-only")
		}
		for _, result := range report.Results {
			results[result.Name] = result
		}
	}
	files := map[string]string{}
	resources := 1 // The administrator adapter is deliberately outside the generic catalog.
	for _, spec := range specs {
		if !spec.DataSourceOnly {
			files[filepath.Join("resources", spec.Name+".md")] = specDocument(spec, false)
			resources++
		}
		files[filepath.Join("data-sources", spec.Name+".md")] = specDocument(spec, true)
	}
	files[filepath.Join("resources", "administrator.md")] = administratorDocument()
	files[filepath.Join("data-sources", "device.md")] = deviceDocument()
	files["capabilities.md"] = capabilitiesDocument(specs, resources, report, results)
	for relative, content := range files {
		path := filepath.Join(*output, relative)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return errors.New("cannot create the documentation directory")
		}
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			return errors.New("cannot write generated documentation")
		}
	}
	// Only remove files bearing this generator's marker; handwritten docs are preserved.
	for _, directory := range []string{"resources", "data-sources"} {
		entries, err := os.ReadDir(filepath.Join(*output, directory))
		if err != nil {
			return errors.New("cannot inspect generated documentation")
		}
		for _, entry := range entries {
			relative := filepath.Join(directory, entry.Name())
			if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") || files[relative] != "" {
				continue
			}
			path := filepath.Join(*output, relative)
			content, err := os.ReadFile(path)
			if err == nil && strings.Contains(string(content), generatedMarker) {
				if err := os.Remove(path); err != nil {
					return errors.New("cannot remove a stale generated document")
				}
			}
		}
	}
	fmt.Printf("Generated %d resource references, %d data-source references, and the capability matrix. No router connection was made.\n", resources, len(specs)+1)
	return nil
}

func heading(title, description string) *strings.Builder {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n# %s\n\n%s\n", generatedMarker, title, description)
	return &b
}

func specDocument(spec catalog.Spec, dataSource bool) string {
	kind := "Resource"
	if dataSource {
		kind = "Data Source"
	}
	b := heading("tplinkrouter_"+spec.Name+" ("+kind+")", spec.Description)
	fmt.Fprintf(b, "\n## 范围与行为\n\n- 分类：%s。\n- SLP 读取对象：`%s`。\n- 管理页面证据：`%s`。\n", cell(spec.Category), objectPath(spec), sourcePath(spec.Source))
	if spec.Capability != "" {
		fmt.Fprintf(b, "- 需要固件能力：`%s`。\n", spec.Capability)
	}
	if dataSource {
		b.WriteString("- 只读查询，不修改运行配置，也不执行保存。秘密写入字段不暴露为读取属性。\n")
		if spec.Mode != catalog.Settings {
			b.WriteString("- 返回全部匹配条目；筛选由此类型固定的设备接口约束决定，无通用 JSON 输入或选择器。\n")
		}
	} else {
		fmt.Fprintf(b, "- 生命周期：%s\n", lifecycle(spec))
		b.WriteString("- 未配置的可选计算属性保留设备当前值；显式清空须使用该属性支持的空值。\n- `auto_save = false` 是 Provider 默认值；启用保存会保存设备全部未保存变更。\n- 当前交付的真实设备验收仅包含读取与导入/计划检查，不代表写入生命周期已经实机验证。\n")
	}
	if spec.Notes != "" {
		fmt.Fprintf(b, "\n%s\n", spec.Notes)
	}
	b.WriteString("\n## 属性\n\n| 属性 | Terraform 类型 | 要求 | 敏感 | 说明 |\n| --- | --- | --- | --- | --- |\n")
	if dataSource {
		writeFieldRow(b, "id", "string", "只读", false, "此读取结果的稳定标识。")
		if spec.Mode == catalog.Settings {
			writeFields(b, spec.Fields, "", true, false)
		} else {
			writeFieldRow(b, "row_count", "number (int64)", "只读", false, "返回的条目数量。")
			writeFieldRow(b, "items", "list(object)", "只读", false, "设备返回的全部匹配条目。")
			writeFieldRow(b, "items[].id", "string", "只读", false, "用于资源导入的条目标识。")
			writeFields(b, spec.Fields, "items[].", true, false)
		}
	} else {
		writeFieldRow(b, "id", "string", "只读", false, "资源的稳定设备标识；参考下方导入语义。")
		if spec.Mode == catalog.Ruleset {
			writeFieldRow(b, "rules", "list(object)", "必填", false, "完整且有序的用户规则列表。应用时删除省略的用户规则，保留固件内置规则。")
			writeFields(b, spec.Fields, "rules[].", false, false)
		} else {
			writeFields(b, spec.Fields, "", false, false)
		}
		b.WriteString("\n## 导入\n\n")
		fmt.Fprintf(b, "%s\n\n```shell\nterraform import tplinkrouter_%s.example %s\n```\n", importDescription(spec), spec.Name, importExample(spec))
		if hasSecrets(spec.Fields) {
			b.WriteString("\n导入不会读取或设置秘密，秘密及其版本初始为空。要保留现值，省略秘密与版本；要有意设置秘密，同时提供 write-only 字段并增加对应 `_version`。秘密不进入状态，设备外部秘密变化无法通过读取检测。\n")
		}
	}
	return b.String()
}

func writeFields(b *strings.Builder, fields []catalog.Field, prefix string, readOnly, inheritedSensitive bool) {
	for _, field := range fields {
		if readOnly && field.WriteOnly {
			continue
		}
		requirement := "可选 + 计算"
		if field.Required {
			requirement = "必填"
		}
		if field.ReadOnly || readOnly {
			requirement = "只读"
		} else if field.WriteOnly {
			requirement = "可选，仅写入"
			if field.Required {
				requirement = "必填，仅写入"
			}
		}
		description := field.Description
		if field.Wire != "" && field.Wire != field.Name {
			description += " SLP 字段：`" + field.Wire + "`。"
		}
		if field.Section != "" {
			description += " SLP 分区：`" + field.Section + "`。"
		}
		if field.Default != nil {
			encoded, _ := json.Marshal(field.Default)
			description += " 默认值：`" + string(encoded) + "`。"
		}
		if len(field.Enum) > 0 {
			description += " 可选值：`" + strings.Join(field.Enum, "`, `") + "`。"
		}
		if field.Format != "" {
			description += " 格式：`" + field.Format + "`。"
		}
		if field.MaxLength > 0 {
			description += fmt.Sprintf(" 最多 %d 个字符。", field.MaxLength)
		}
		if field.Kind == catalog.Int && field.Max > field.Min {
			description += fmt.Sprintf(" 范围：%d–%d。", field.Min, field.Max)
		}
		if field.RequiresReplace && !readOnly {
			description += " 修改时替换资源。"
		}
		sensitive := inheritedSensitive || field.Sensitive
		writeFieldRow(b, prefix+field.Name, typeName(field.Kind), requirement, sensitive, description)
		if field.WriteOnly {
			writeFieldRow(b, prefix+field.Name+"_version", "number (int64)", "可选", false, "增加此版本以有意设置对应秘密；仅更改秘密值不会产生 Terraform 计划差异。")
		}
		if len(field.Fields) > 0 {
			childPrefix := prefix + field.Name + "."
			if field.Kind == catalog.ObjectList || field.Kind == catalog.ObjectSet {
				childPrefix = prefix + field.Name + "[]."
			}
			writeFields(b, field.Fields, childPrefix, readOnly, sensitive)
		}
	}
}

func writeFieldRow(b *strings.Builder, name, kind, requirement string, sensitive bool, description string) {
	secret := "否"
	if sensitive {
		secret = "是"
	}
	fmt.Fprintf(b, "| `%s` | `%s` | %s | %s | %s |\n", cell(name), cell(kind), cell(requirement), secret, cell(description))
}

func typeName(kind catalog.Kind) string {
	switch kind {
	case catalog.Bool:
		return "bool"
	case catalog.Int:
		return "number (int64)"
	case catalog.StringList:
		return "list(string)"
	case catalog.StringSet:
		return "set(string)"
	case catalog.Object:
		return "object"
	case catalog.ObjectList:
		return "list(object)"
	case catalog.ObjectSet:
		return "set(object)"
	default:
		return "string"
	}
}

func objectPath(spec catalog.Spec) string {
	selector := spec.Table
	if spec.Mode == catalog.Settings {
		selector = spec.Section
	}
	if spec.Resolve != nil {
		return spec.Module + "." + selector + " (按设备模式解析)"
	}
	return spec.Module + "." + selector
}

func sourcePath(source string) string {
	if source == "" {
		return "未填写"
	}
	if !strings.HasPrefix(source, "/") && !strings.Contains(source, "://") {
		return "/userrpm/" + source
	}
	return source
}

func lifecycle(spec catalog.Spec) string {
	switch spec.Mode {
	case catalog.Settings:
		return "管理现有单例设置；销毁仅停止 Terraform 管理，保留设备设置。"
	case catalog.Existing:
		return "导入并管理现有硬件/接口条目；销毁仅停止管理，不删除硬件或重置设置。"
	case catalog.Ruleset:
		return "独占管理完整有序用户规则表；更新会移除省略的用户规则；销毁清空用户规则并保留内置规则。"
	default:
		return "创建、读取、原位更新或删除一个独立条目；不级联删除引用对象，固件内置条目受保护。"
	}
}

func importDescription(spec catalog.Spec) string {
	switch spec.Mode {
	case catalog.Settings:
		return "固定导入 ID 为 `settings`。导入只读取已有配置，不修改设备。"
	case catalog.Ruleset:
		return "固定导入 ID 为 `ruleset`。导入完整用户规则表并保留其顺序；使用一个资源独占管理此表。"
	default:
		if len(spec.IDFields) > 0 {
			return "导入 ID 依次由 `" + strings.Join(spec.IDFields, "`, `") + "` 组成。每个值分别进行 URL 路径编码，再用 `/` 连接；不能使用可变行号。"
		}
		if spec.IDField != "" {
			return "导入 ID 为设备字段 `" + spec.IDField + "` 的值。可从对应数据源的 `items[].id` 获取；不能使用列表下标。"
		}
		return "导入 ID 为设备返回的持久 section 名称。可从对应数据源的 `items[].id` 获取；用户可见名称和列表下标不一定是导入 ID。"
	}
}

func importExample(spec catalog.Spec) string {
	if spec.Mode == catalog.Settings {
		return "settings"
	}
	if spec.Mode == catalog.Ruleset {
		return "ruleset"
	}
	if len(spec.IDFields) > 0 {
		return strconv.Quote(strings.Join(spec.IDFields, "/"))
	}
	return "\"<device-id>\""
}

func hasSecrets(fields []catalog.Field) bool {
	for _, field := range fields {
		if field.WriteOnly || hasSecrets(field.Fields) {
			return true
		}
	}
	return false
}

func cell(text string) string {
	text = strings.ReplaceAll(text, "|", "\\|")
	text = strings.ReplaceAll(text, "\r", "")
	return strings.ReplaceAll(text, "\n", "<br>")
}

