	spec := catalog.Spec{Name: "administrator", Description: "管理当前路由器管理员的登录凭据。", Category: "System", Module: "administration", Section: "modify_login_pwd", Mode: catalog.Settings, Source: "/userrpm/account_config.htm", Fields: []catalog.Field{username, password}, Notes: "更改凭据后，Provider 在内存中验证并切换到新会话；下一次执行 Terraform 前，需同步更新 env_file 或 Provider 使用的凭据来源。Provider 不会修改 .env。销毁保留账户和密码。"}
